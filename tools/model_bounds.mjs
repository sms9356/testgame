// Regenerate conservative authored bounds without loading textures or WebGL.
import fs from 'node:fs';
import path from 'node:path';
import * as THREE from '../vendor/three.module.js';
const root = path.resolve(new URL('../assets/models/', import.meta.url).pathname), result = {};
for (const dir of fs.readdirSync(root, {withFileTypes:true}).filter(d=>d.isDirectory())) {
  const folder=path.join(root,dir.name);
  for (const name of fs.readdirSync(folder).filter(n=>/\.(glb|gltf)$/.test(n))) {
    const file=path.join(folder,name), data=fs.readFileSync(file);
    const json=name.endsWith('.glb')?JSON.parse(data.subarray(20,20+data.readUInt32LE(12)).toString()):JSON.parse(data.toString());
    const box=new THREE.Box3();
    const walk=(index,parent)=>{const node=json.nodes[index],local=new THREE.Matrix4();
      if(node.matrix)local.fromArray(node.matrix);else local.compose(new THREE.Vector3().fromArray(node.translation||[0,0,0]),new THREE.Quaternion().fromArray(node.rotation||[0,0,0,1]),new THREE.Vector3().fromArray(node.scale||[1,1,1]));
      const matrix=parent.clone().multiply(local);
      for(const primitive of json.meshes?.[node.mesh]?.primitives||[]){const a=json.accessors[primitive.attributes.POSITION];if(a.min&&a.max)box.union(new THREE.Box3(new THREE.Vector3().fromArray(a.min),new THREE.Vector3().fromArray(a.max)).applyMatrix4(matrix));}
      for(const child of node.children||[])walk(child,matrix);
    };
    for(const node of json.scenes?.[json.scene||0]?.nodes||[])walk(node,new THREE.Matrix4());
    if(box.isEmpty())continue;
    if(dir.name==='pr')box.applyMatrix4(new THREE.Matrix4().makeRotationX(-Math.PI/2));
    const key=name.endsWith('.gltf')?dir.name:`${dir.name}/${name.slice(0,-4)}`;
    result[key]=[...box.min.toArray(),...box.max.toArray()].map(v=>+v.toFixed(4));
  }
}
fs.writeFileSync(new URL('../modelBounds.js',import.meta.url),`// Generated by tools/model_bounds.mjs from authored mesh transforms.\nexport const MODEL_BOUNDS = ${JSON.stringify(result,null,2)};\n`);
console.log('Bounded models:',Object.keys(result).length);
